"""Generate the leaderboard page from the result files under ``results/``.

Every number on the page comes from a result file that validates against the schema; nothing is typed by
hand. Layout: ``results/<suite>/<submission>/**/*.json`` where ``<submission>`` is a dated directory one pull
request adds (``2026-11-27-poc``, ``2026-12-03-acme-vla``). The page lists, per suite, the methods x tiers
matrix over every submission, then one block per submission with its per-task rows and provenance::

    python tools/bench/leaderboard.py            # writes docs/source/dataset_benchmark/benchmark/leaderboard.md
    python tools/bench/leaderboard.py --check    # exits 1 if the page is stale (CI)
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "packages" / "metasim"))
RESULTS = REPO / "results"
PAGE = REPO / "docs" / "source" / "dataset_benchmark" / "benchmark" / "leaderboard.md"


def load_all():
    import json

    from metasim.bench import BenchmarkResult, validate_result

    by_suite: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))
    for f in sorted(RESULTS.rglob("*.json")):
        rel = f.relative_to(RESULTS)
        if (
            len(rel.parts) < 3 or rel.parts[0] == "robots"
        ):  # results/robots/ holds robot check / parity runs, not results
            continue
        suite, submission = rel.parts[0], rel.parts[1]
        data = json.loads(f.read_text())
        validate_result(data)  # a bad file fails the build, not the reader
        by_suite[suite][submission].append(BenchmarkResult.load(f))
    return by_suite


def render(by_suite) -> str:
    from metasim.bench import matrix, summarize

    out = [
        "# Leaderboard",
        "",
        "Generated by `tools/bench/leaderboard.py` from the result files under `results/`; do not edit by hand.",
        "A row enters by pull request: add the result files of one run under `results/<suite>/<date>-<name>/`.",
        "Every file validates against the result schema and records the protocol, the information-access tier,",
        "the simulator, the checkpoint hash and the command, so a number can always be traced to its run.",
        "Methods are comparable within a tier column only; the `*` marks a method scored on fewer tasks than the suite.",
        "",
    ]
    for suite, submissions in sorted(by_suite.items()):
        results = [r for rs in submissions.values() for r in rs]
        out += [
            f"## {suite}",
            "",
            f"{len(submissions)} submission(s), {len(results)} result files.",
            "",
            "### Methods x tiers",
            "",
            matrix(results),
            "",
        ]
        for name, rs in sorted(submissions.items()):
            sims = sorted({r.simulator for r in rs})
            policies = sorted({str(r.policy.get("name")) for r in rs})
            episodes = sum(len(r.episodes) for r in rs)
            prov = rs[0].provenance if rs else {}
            versions = prov.get("versions") or prov.get("packages") or {}
            out += [
                f"### {name}",
                "",
                f"- simulators: {', '.join(sims)}; policies: {', '.join(policies)}; {episodes} episodes in {len(rs)} files",
                f"- MetaSim {prov.get('metasim_version', prov.get('version', '?'))}, commit `{str(prov.get('git_commit', '?'))[:10]}`"
                + (
                    f", {', '.join(f'{k} {v}' for k, v in list(versions.items())[:3])}"
                    if isinstance(versions, dict) and versions
                    else ""
                ),
                "",
                summarize(rs),
                "",
            ]
    return "\n".join(out).rstrip() + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when the committed page differs from the generated one")
    args = ap.parse_args(argv)
    page = render(load_all())
    if args.check:
        current = PAGE.read_text() if PAGE.exists() else ""
        if current != page:
            sys.stderr.write("leaderboard.md is stale: run python tools/bench/leaderboard.py\n")
            return 1
        return 0
    PAGE.write_text(page)
    sys.stderr.write(f"{PAGE}: {len(page.splitlines())} lines\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
